#!/usr/bin/env python3
"""Generate one-LAB-per-RO placement; final legality is checked by Quartus Fitter."""

import csv
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
QUARTUS = ROOT / "quartus"
GATES = ["nand_out", *[f"not_{stage}" for stage in range(1, 10)]]


def main():
    # Device-specific LAB columns confirmed by the 5CGXFC5C6F27C7 Fitter.
    # Revalidate the map if changing device, coordinates, or RO hierarchy.
    columns = [11, 13, 15, 17, 21, 23]
    locations = [(x, y) for x in columns for y in range(2, 13)][:64]
    rows = []
    lines = ["# Generated by scripts/generate_placement.py; 64 ROs, 640 gate locations."]
    for ro, (x, y) in enumerate(locations):
        for stage, gate in enumerate(GATES):
            target = f"PUF:puf_inst|RO_basic:gen_Ro[{ro}].ro_inst|{gate}"
            location = f"LABCELL_X{x}_Y{y}_N{stage * 6}"
            lines.append(f"set_location_assignment {location} -to {{{target}}}")
            rows.append({"ro": ro, "group": ro // 16, "gate": gate,
                         "x": x, "y": y, "n": stage * 6, "location": location,
                         "target": target})
    (QUARTUS / "ro_placement.tcl").write_text("\n".join(lines) + "\n")
    with (QUARTUS / "ro_placement.csv").open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    print(f"Generated {len(rows)} assignments in {len(locations)} distinct LABs")


if __name__ == "__main__":
    main()
